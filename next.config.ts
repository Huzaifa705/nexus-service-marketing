import type { NextConfig } from "next";

// Baseline security headers. A Content-Security-Policy is added in Node 13 once the
// pages exist and can be tested; HSTS is applied by the hosting platform.
const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
];

// Cache Components and partial prefetching (enabled by the generator) are switched off on
// purpose: every NEXUS page shows per-user data, so rendering stays dynamic with no implicit
// caching of user or financial data. See decision D-27 in docs/decision-log.md.
const nextConfig: NextConfig = {
  poweredByHeader: false,
  // Tailwind CSS v4 processing under Turbopack (as generated by create-next-app).
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
